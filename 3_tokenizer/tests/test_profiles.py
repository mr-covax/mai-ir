@pytest.mark.parametrize("nested", [True, False])
def test_cppreference(nested):
    content = """
        <div class="t-navbar">Standard library menu</div>
        <div id="toc">Contents</div>
        <h2>Memory order<span class="mw-editsection">edit</span></h2>
        <p>Use std::atomic.</p>
        <pre>std::atomic&lt;int&gt; value{0};</pre>
    """
    if nested:
        content = f'<div class="mw-parser-output">{content}</div>'

    html = f'<h1 id="firstHeading">Memory model</h1><div id="mw-content-text">{content}</div>'
    document = extract_document(html, "cppreference")

    assert document.title == "Memory model"
    assert document.text == "Memory order\n\nUse std::atomic.\n\nstd::atomic<int> value{0};"


def test_man7_boundaries():
    html = """
        <body>
            <div>Training advertisement</div>
            <h1>mmap(2) — Linux manual page</h1>
            <table class="sec-table"><tr><td>NAME SYNOPSIS</td></tr></table>
            <pre>mmap - map memory</pre>
            <h2>SYNOPSIS <a href="#top"><span class="top-link">top</span></a></h2>
            <pre>    void *mmap(void *addr);</pre>
            <hr class="end-man-text">
            <p>Advertisement after manual</p>
            <div class="footer">HTML rendering created today</div>
        </body>
    """

    document = extract_document(html, "man7")

    assert document.title == "mmap(2) — Linux manual page"
    assert document.text == (
        "mmap(2) — Linux manual page\n\nmmap - map memory\n\nSYNOPSIS\n\n    void *mmap(void *addr);"
    )


def test_man7_requires_end_marker():
    with pytest.raises(ValueError, match="Main content not found"):
        extract_document("<body><h1>Not a manual</h1><p>Noise</p></body>", "man7")


def test_unknown_source():
    with pytest.raises(ValueError, match="Unsupported source"):
        extract_document("<body>Text</body>", "unknown")


@pytest.mark.parametrize("source", ["llvm", "freebsd-docs", "cppreference", "man7"])
def test_no_body_fallback(source):
    with pytest.raises(ValueError, match="Main content not found"):
        extract_document("<body><p>Site navigation</p></body>", source)
