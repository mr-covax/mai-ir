import pytest

from tokenizer.extraction import extract_document


@pytest.mark.parametrize(
    "source", ["linux-kernel", "llvm", "clang", "lld", "lldb", "llvm-libc", "llvm-libcxx"]
)
def test_sphinx_sources(source):
    html = """
        <aside>Sidebar</aside>
        <article role="main">
            <h1>Memory<a class="headerlink">#</a></h1>
            <div class="toctree-wrapper">Table of contents</div>
            <p>Allocate with <code>malloc()</code>.</p>
            <button>Copy</button><svg>Icon</svg>
            <pre>    free(ptr);</pre>
        </article>
    """

    document = extract_document(html, source)

    assert document.title == "Memory"
    assert document.text == "Memory\n\nAllocate with malloc().\n\n    free(ptr);"


